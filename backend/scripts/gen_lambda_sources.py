"""Generate the Terraform files that carry the Lambda code, from backend/src/*.py.

Why: the Terraform workspace that runs `plan`/`apply` accepts only .tf/.tfvars files,
and its upload endpoint rejects request bodies over ~8 KB. So each Python file travels
as one or more heredoc strings in small .tf files:

    lambda_src_<module>.tf            whole file, if it fits in one chunk
    lambda_src_<module>_<n>.tf        part n, if it doesn't
    lambda_sources.tf                 joins the parts back into local.lambda_sources

`archive_file` in lambda.tf then zips local.lambda_sources. backend/src stays the
source of truth. Re-run after any handler change:

    python backend/scripts/gen_lambda_sources.py          # write
    python backend/scripts/gen_lambda_sources.py --check  # fail if stale (tests run this)
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
TF = ROOT / "terraform"
DELIM = "PYSRC"
CHUNK_BYTES = 3000  # escaped text per .tf file; well under the ~8 KB upload limit
GENERATED_GLOB = "lambda_src_*.tf"


def escape(text: str) -> str:
    # HCL heredocs are templates: `${` and `%{` start interpolation/directives.
    return text.replace("${", "$${").replace("%{", "%%{")


def unescape(text: str) -> str:
    return text.replace("$${", "${").replace("%%{", "%{")


def chunk_lines(text: str, limit: int = CHUNK_BYTES) -> list[str]:
    """Split at line boundaries so each escaped chunk stays under `limit` bytes.
    Joining the chunks gives back `text` exactly."""
    chunks: list[str] = []
    current = ""
    for line in text.splitlines(keepends=True):
        if current and len(escape(current + line).encode()) > limit:
            chunks.append(current)
            current = ""
        current += line
    if current:
        chunks.append(current)
    return chunks


def render() -> dict[str, str]:
    """Return {filename: content} for every generated .tf file."""
    out: dict[str, str] = {}
    entries: list[str] = []
    for path in sorted(SRC.glob("*.py")):
        stem = path.stem
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if not text.endswith("\n"):
            text += "\n"
        if any(line.strip() == DELIM for line in text.splitlines()):
            raise SystemExit(f"{path.name} contains a line equal to the heredoc delimiter {DELIM!r}")

        chunks = chunk_lines(text)
        names = [f"lambda_src_{stem}"] if len(chunks) == 1 else [
            f"lambda_src_{stem}_{i}" for i in range(1, len(chunks) + 1)
        ]
        for i, (name, chunk) in enumerate(zip(names, chunks), start=1):
            part = "" if len(chunks) == 1 else f" (part {i} of {len(chunks)})"
            out[f"{name}.tf"] = (
                f"# GENERATED by backend/scripts/gen_lambda_sources.py from backend/src/{path.name}{part}. Do not edit.\n"
                "\n"
                "locals {\n"
                f"  {name} = <<{DELIM}\n"
                f"{escape(chunk)}{DELIM}\n"
                "}\n"
            )
        joined = ", ".join(f"local.{n}" for n in names)
        entries.append(f'    "{path.name}" = join("", [{joined}])')

    out["lambda_sources.tf"] = (
        "# GENERATED by backend/scripts/gen_lambda_sources.py. Do not edit.\n"
        "# Reassembles each handler file from its lambda_src_*.tf part(s).\n"
        "\n"
        "locals {\n"
        "  lambda_sources = {\n" + "\n".join(entries) + "\n  }\n}\n"
    )
    return out


def main() -> int:
    files = render()
    existing = {p.name for p in TF.glob(GENERATED_GLOB)} | ({"lambda_sources.tf"} & {p.name for p in TF.glob("*.tf")})
    if "--check" in sys.argv:
        stale = [n for n, c in files.items() if not (TF / n).exists() or (TF / n).read_text(encoding="utf-8") != c]
        extra = sorted(existing - set(files))
        if stale or extra:
            print(f"Generated Terraform is stale (changed: {stale}, leftover: {extra}). "
                  "Run: python backend/scripts/gen_lambda_sources.py")
            return 1
        print("Generated Lambda source files are up to date.")
        return 0
    for name in sorted(existing - set(files)):
        (TF / name).unlink()
        print(f"removed backend/terraform/{name}")
    for name, content in files.items():
        (TF / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote backend/terraform/{name} ({len(content.encode())} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
